const SIDED = new Set(['clavicle', 'scapula', 'arm', 'ulna', 'radius', 'hand', 'femur', 'shank', 'talus', 'foot', 'thumbMeta', 'thumbProx', 'thumbDist', 'indexProx', 'middleProx', 'ringProx', 'littleProx', 'middleDist']);

export const DEPTHS = ['surface', 'mid', 'deep'];
export const DEPTH_TEXT = { surface: '表淺', mid: '肌肉層', deep: '深處' };

export const isMidlineZone = zoneId => ZONES[zoneId].p[0] === 0;

// 區域在某一側的骨段與座標
export function zoneAt(zoneId, side) {
  const z = ZONES[zoneId];
  const flip = side === 'r';
  return {
    id: z.id,
    label: z.label,
    seg: SIDED.has(z.seg) ? `${z.seg}.${flip ? 'r' : 'l'}` : z.seg,
    pos: [flip ? -z.p[0] : z.p[0], z.p[1], z.p[2]],
    radius: z.radius,
    depth: z.depth,
  };
}

// 某條肌肉（某一側）的轉移痛區域；中線肌肉（橫膈、骨盆底）左右都標
export function referredZones(muscleId, side) {
  const ids = REFERRED[muscleId] ?? [];
  const out = [];
  for (const id of ids) {
    if (isMidlineZone(id)) out.push(zoneAt(id, 'l'));
    else if (side === 'm') out.push(zoneAt(id, 'l'), zoneAt(id, 'r'));
    else out.push(zoneAt(id, side));
  }
  return out;
}

export function hasReferredZones(muscleId) {
  return Boolean(REFERRED[muscleId]?.length);
}
